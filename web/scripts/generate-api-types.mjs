// Generates src/api/generated/api-types.ts from the backend's OpenAPI document
// (server_dotnet/tests/Contracts/openapi-v1.json, itself checked by OpenApiContractTests).
//
//   node scripts/generate-api-types.mjs          # rewrite the file
//   node scripts/generate-api-types.mjs --check  # exit 1 if it is stale (used by tests)
//
// A small purpose-built generator: the API's schemas only use objects, arrays, primitives, nullable,
// $ref and string-keyed maps. (openapi-typescript does not support TypeScript 6 yet.)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(web, '../server_dotnet/tests/Contracts/openapi-v1.json')
const target = join(web, 'src/api/generated/api-types.ts')
const API_PREFIX = '/api/v1'

const refName = ref => ref.replace('#/components/schemas/', '')

function typeOf(schema) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown'
  if (schema.$ref) return refName(schema.$ref)
  const nullable = schema.nullable ? ' | null' : ''
  if (schema.allOf?.length === 1) return typeOf(schema.allOf[0]) + nullable
  switch (schema.type) {
    case 'integer':
    case 'number': return 'number' + nullable
    case 'boolean': return 'boolean' + nullable
    case 'string': return (schema.enum ? schema.enum.map(value => JSON.stringify(value)).join(' | ') : 'string') + nullable
    case 'array': return `Array<${typeOf(schema.items)}>` + nullable
    case 'object':
    case undefined:
      if (schema.properties) return inlineObject(schema, false) + nullable
      if (schema.additionalProperties) {
        const value = schema.additionalProperties === true ? 'unknown' : typeOf(schema.additionalProperties)
        return `Record<string, ${value}>` + nullable
      }
      return 'Record<string, unknown>' + nullable
    default: return 'unknown'
  }
}

function inlineObject(schema, requestOnly, indent = '') {
  const required = new Set(schema.required ?? [])
  const lines = Object.entries(schema.properties ?? {}).map(([name, property]) => {
    // Requests may leave out nullable members; responses always carry every required member.
    const optional = !required.has(name) || (requestOnly && property.nullable)
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
    return `${indent}  ${key}${optional ? '?' : ''}: ${typeOf(property)}`
  })
  return `{\n${lines.join('\n')}\n${indent}}`
}

/** Schema names referenced (transitively) from response bodies. */
function responseSchemas(document) {
  const found = new Set()
  const visit = schema => {
    if (!schema || typeof schema !== 'object') return
    if (schema.$ref) {
      const name = refName(schema.$ref)
      if (found.has(name)) return
      found.add(name)
      visit(document.components.schemas[name])
      return
    }
    for (const value of Object.values(schema)) if (value && typeof value === 'object') visit(value)
  }
  for (const item of Object.values(document.paths)) {
    for (const operation of Object.values(item)) {
      for (const response of Object.values(operation.responses ?? {})) visit(response.content)
    }
  }
  return found
}

export function render() {
  const document = JSON.parse(readFileSync(source, 'utf8'))
  const schemas = document.components?.schemas ?? {}
  const usedInResponses = responseSchemas(document)
  const out = [
    '// Generated by scripts/generate-api-types.mjs from server_dotnet/tests/Contracts/openapi-v1.json. Do not edit.',
    '/* eslint-disable */',
    '',
  ]
  for (const name of Object.keys(schemas).sort()) {
    const schema = schemas[name]
    const requestOnly = !usedInResponses.has(name)
    out.push(schema.properties || schema.type === 'object'
      ? `export interface ${name} ${inlineObject(schema, requestOnly)}`
      : `export type ${name} = ${typeOf(schema)}`)
    out.push('')
  }
  out.push('/** Success body of each endpoint, keyed by "METHOD path" relative to /api/v1 (the axios baseURL). */')
  out.push('export interface ApiResponses {')
  for (const route of Object.keys(document.paths).sort()) {
    for (const [method, operation] of Object.entries(document.paths[route]).sort()) {
      const success = Object.entries(operation.responses ?? {}).find(([status]) => status.startsWith('2'))
      if (!success) continue
      const [status, response] = success
      const schema = response.content?.['application/json']?.schema
      const type = status === '204' ? 'void' : schema ? typeOf(schema) : 'Blob'
      out.push(`  ${JSON.stringify(`${method.toUpperCase()} ${route.slice(API_PREFIX.length)}`)}: ${type}`)
    }
  }
  out.push('}')
  out.push('')
  out.push('export type ApiRoute = keyof ApiResponses')
  out.push('')
  return out.join('\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = render()
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== next) {
      console.error('src/api/generated/api-types.ts is stale; run: npm run generate:api-types')
      process.exit(1)
    }
  } else {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, next)
    console.log(`wrote ${relative(web, target)}`)
  }
}
