// Generates src/styles/arco-components.ts: the Arco stylesheets this app needs, in the same order as the
// full dist/css/arco.css. Loading each component's css.js instead would put a component's dependencies
// (e.g. Grid, Input) *before* it, changing which equal-specificity rule wins and shifting layouts.
//
//   node scripts/generate-arco-styles.mjs          # rewrite the file
//   node scripts/generate-arco-styles.mjs --check  # exit 1 if the file is stale (used by tests)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const es = join(web, 'node_modules/@arco-design/web-react/es')
const target = join(web, 'src/styles/arco-components.ts')

function sourceFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const full = join(directory, entry.name)
    if (entry.isDirectory()) return ['test', '__tests__'].includes(entry.name) ? [] : sourceFiles(full)
    return /\.(ts|tsx)$/.test(entry.name) && !/\.(test|spec)\.(ts|tsx)$/.test(entry.name) ? [full] : []
  })
}

/** Components imported from '@arco-design/web-react' anywhere in src (multi-line imports included). */
export function importedComponents() {
  const names = new Set()
  for (const file of sourceFiles(join(web, 'src'))) {
    const source = readFileSync(file, 'utf8')
    for (const [, list] of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*'@arco-design\/web-react'/g)) {
      for (const raw of list.split(',')) {
        const name = raw.replace(/^\s*type\s+/, '').split(/\s+as\s+/)[0].trim()
        if (/^[A-Z][A-Za-z]+$/.test(name) && existsSync(join(es, name, 'style/css.js'))) names.add(name)
      }
    }
  }
  return [...names].sort()
}

/** Every index.css reachable from the components' css.js files. */
function stylesheets(components) {
  const sheets = new Set()
  const visited = new Set()
  const visit = cssJs => {
    if (visited.has(cssJs)) return
    visited.add(cssJs)
    for (const [, spec] of readFileSync(cssJs, 'utf8').matchAll(/import '([^']+)'/g)) {
      const path = resolve(dirname(cssJs), spec)
      if (spec.endsWith('.css')) sheets.add(path)
      else visit(path)
    }
  }
  for (const name of components) visit(join(es, name, 'style/css.js'))
  return [...sheets]
}

/** Order sheets as the full bundle does: base styles, shared _class styles, then components A-Z. */
function bundleOrder(path) {
  const rel = relative(es, path).replace(/\\/g, '/')
  if (rel === 'style/index.css') return '0'
  if (rel.startsWith('_class/')) return '1' + rel
  return '2' + rel.toLowerCase()
}

export function render() {
  const components = importedComponents()
  const lines = stylesheets(components)
    .sort((a, b) => bundleOrder(a).localeCompare(bundleOrder(b)))
    .map(path => `import '@arco-design/web-react/es/${relative(es, path).replace(/\\/g, '/')}'`)
  return [
    '// Generated by scripts/generate-arco-styles.mjs from the Arco components imported in src. Do not edit.',
    '// Only the needed stylesheets, in the full arco.css order so the cascade matches the complete bundle.',
    `// Components: ${components.join(', ')}`,
    ...lines,
    '',
  ].join('\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = render()
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== next) {
      console.error('src/styles/arco-components.ts is stale; run: node scripts/generate-arco-styles.mjs')
      process.exit(1)
    }
  } else {
    writeFileSync(target, next)
    console.log(`wrote ${relative(web, target)}`)
  }
}
